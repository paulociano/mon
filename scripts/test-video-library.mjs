import fs from 'node:fs';
import assert from 'node:assert/strict';
const app=fs.readFileSync('app.js','utf8');
const html=fs.readFileSync('index.html','utf8');
const js=fs.readFileSync('features/videos.js','utf8');
const css=fs.readFileSync('features/videos.css','utf8');

assert.ok(app.includes("videos:['./features/videos.js']"));
assert.ok(app.includes("videos:['./features/videos.css']"));
assert.ok(html.includes('data-view="videos"'));
assert.ok(html.includes('data-icon="映" onclick="go(\'videos\')"'),'Video Library should be discoverable from Practice Hub');
assert.ok(html.includes('id="videoGrid"'));
assert.ok(html.includes('id="videoStage"'));
assert.ok(html.includes('id="videoModal" class="video-modal" aria-hidden="true" hidden'),'video modal must be natively hidden before lazy CSS loads');
assert.ok(html.includes('id="videoExternalLink"'),'video modal needs an external playback fallback');
assert.ok(js.includes('youtube-nocookie.com/embed/'));
assert.ok(js.includes("modal.hidden=false"),'opening a video must unhide the native modal');
assert.ok(js.includes("modal.hidden=true"),'closing a video must restore native hidden state');
assert.ok(js.includes("youtube.com/watch?v="),'video player needs a YouTube fallback link');
assert.ok(js.includes('referrerpolicy="strict-origin-when-cross-origin"'),'video iframe should use an explicit referrer policy');
assert.ok(js.includes('loading="lazy"'));
assert.ok(!html.includes('<iframe'),'no video iframe should exist before user action');
assert.ok(js.includes("source:'Japan Foundation · Irodori'"));
assert.ok(css.includes('.video-modal[hidden]{display:none!important}'));
assert.ok(css.includes('.video-fallback'));
console.log('MON Video Library contracts passed');
